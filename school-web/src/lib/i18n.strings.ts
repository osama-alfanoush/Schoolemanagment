/** Projects the paired tree onto one language: 0 = English, 1 = Arabic. */
export function localeTree(index: 0 | 1): Record<string, unknown> {
  const walk = (node: Node): Record<string, unknown> => {
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node)) {
      out[key] = isPair(value) ? value[index] : walk(value);
    }
    return out;
  };
  return walk(strings);
}
