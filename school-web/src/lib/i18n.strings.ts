/**
 * Translations kept as `[english, arabic]` pairs.
 *
 * The original catalogue holds one whole tree per language, which works while
 * the tree is small but makes a missing or drifted Arabic string invisible in
 * review. Pairing the two languages on one line means a translator can see at a
 * glance what is untranslated, and a key can never exist in one tree only.
 *
 * `localeTree()` splits this back into the per-language shape i18next expects.
 */

export type Pair = readonly [en: string, ar: string];
type Node = { [key: string]: Pair | Node };

const isPair = (value: Pair | Node): value is Pair =>
  Array.isArray(value) && value.length === 2 && typeof value[0] === "string";

